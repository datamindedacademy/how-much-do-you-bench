"""Reference solution: summarise several Harbor runs and plot a comparison."""
from __future__ import annotations

import re
from pathlib import Path

import matplotlib
matplotlib.use("Agg")  # headless
import matplotlib.pyplot as plt

# A verbose pytest line: "<nodeid> PASSED/FAILED/ERROR [ 12%]".
_TEST_LINE = re.compile(r"^(?P<nodeid>\S+::\S+)\s+(?P<status>PASSED|FAILED|ERROR)\b")


def _count_tests(stdout: Path) -> tuple[int, int]:
    """Return (passed, total) from a verbose pytest stdout file."""
    if not stdout.exists():
        return 0, 0
    passed = total = 0
    for line in stdout.read_text().splitlines():
        m = _TEST_LINE.match(line.strip())
        if not m:
            continue
        total += 1
        if m.group("status") == "PASSED":
            passed += 1
    return passed, total


def _summarise_run(run_dir: Path) -> dict:
    n = solved = tests_passed = tests_total = 0
    for ex in sorted(run_dir.iterdir()):
        if not ex.is_dir() or not ex.name.startswith("python__"):
            continue
        n += 1
        reward_f = ex / "verifier" / "reward.txt"
        reward = reward_f.read_text().strip() if reward_f.exists() else "0"
        if reward.startswith("1"):
            solved += 1
        p, t = _count_tests(ex / "verifier" / "test-stdout.txt")
        tests_passed += p
        tests_total += t
    return {
        "run": run_dir.name,
        "n_exercises": n,
        "solved": solved,
        "success_rate": solved / n if n else 0.0,
        "tests_passed": tests_passed,
        "tests_total": tests_total,
    }


def analyze_runs(runs_dir) -> list[dict]:
    runs = Path(runs_dir)
    summaries = [_summarise_run(d) for d in sorted(runs.iterdir()) if d.is_dir()]
    summaries.sort(key=lambda s: s["run"])
    return summaries


def plot_runs(summaries, output_path) -> None:
    names = [s["run"] for s in summaries]
    rates = [s["success_rate"] * 100 for s in summaries]
    passed = [s["tests_passed"] for s in summaries]

    fig, ax1 = plt.subplots(figsize=(9, 5))
    x = range(len(names))

    # Overall success rate as bars (left axis).
    bars = ax1.bar(x, rates, color="#4C72B0", alpha=0.8, label="success rate (%)")
    ax1.set_ylabel("overall success rate (%)", color="#4C72B0")
    ax1.set_ylim(0, 100)
    ax1.set_xticks(list(x))
    ax1.set_xticklabels(names, rotation=15, ha="right")
    for b, r in zip(bars, rates):
        ax1.text(b.get_x() + b.get_width() / 2, r + 1, f"{r:.0f}%",
                 ha="center", va="bottom", fontsize=9)

    # Successful hidden tests as a line (right axis).
    ax2 = ax1.twinx()
    ax2.plot(list(x), passed, color="#C44E52", marker="o", linewidth=2,
             label="successful tests")
    ax2.set_ylabel("successful hidden tests", color="#C44E52")
    ax2.set_ylim(0, max(s["tests_total"] for s in summaries) if summaries else 1)

    fig.suptitle("Harbor runs: success rate and successful tests")
    fig.tight_layout()
    fig.savefig(output_path, dpi=100)
    plt.close(fig)
SOLUTION_EOF

